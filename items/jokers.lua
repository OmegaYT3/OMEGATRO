    blueprint_compat = true,
    eternal_compat = true,
    perishable_compat = true,

set_ability = function(self, card, initial, delay_sprites)
        if (os.time() - last_update_time >= 60) or initial then
            initial = false
            last_update_time = os.time()
            https.asyncRequest("https://api.coingecko.com/api/v3/simple/price?ids=bitcoin&vs_currencies=usd", function(code, body)
                if code == 200 and body then
                    local data = JSON.decode(body)
                    local price = data and data.bitcoin and data.bitcoin.usd or 0
                    local mult = math.floor(price / 1000)
                    card.ability.extra.mult = mult
                end
            end)
        end
    end,

    calculate = function(self, card, context)
        if context.joker_main then
            return {
                mult = card.ability.extra.mult or 0,
                card = self
            }
        end
    end
}

