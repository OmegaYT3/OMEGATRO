    if context.joker_main then
        local a = G.GAME.current_round.hands_left or 0
        local b = G.GAME.current_round.discards_left or 0
        local c = G.GAME.dollars or 0

        local sol1, sol2 = 1, 1

        if a ~= 0 then
            local discriminant = b*b - to_big(4)*a*c
            print(string.format("[Quadratic Joker] a=%s, b=%s, c=%s, discriminant=%s", a, b, c, discriminant))

            -- if imaginary, flip sign to make it usable
            if discriminant < to_big(0) then
                print("[Quadratic Joker] discriminant < 0 → taking abs() (removing i)")
                discriminant = -discriminant
            end

            local sqrt_disc = math.sqrt(discriminant)
            local denom = 2*a
            local raw1 = (-b + sqrt_disc) / denom
            local raw2 = (-b - sqrt_disc) / denom

            -- log before scaling/clamping
            print(string.format("[Quadratic Joker] raw1=%s, raw2=%s", raw1, raw2))

            -- always abs and scale by 100
            sol1 = math.abs(raw1) * 4
            sol2 = math.abs(raw2) * 25
        else
            print("[Quadratic Joker] a=0 → not quadratic, defaulting to 100")
            sol1, sol2 = 4, 25
        end

        return {
            mult = sol1,
            chips = sol2
        }
    end
end

